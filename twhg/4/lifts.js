function updateLinearLift(n, l) {
	if(l==null)
		l = level;
	
	if (lifts[l][n].enemyType == "linear") {
		var startX = lifts[l][n].movement[lifts[l][n].stage][0];
		var endX   = lifts[l][n].movement[lifts[l][n].stage][1];
		var startY = lifts[l][n].movement[lifts[l][n].stage][2];
		var endY   = lifts[l][n].movement[lifts[l][n].stage][3];
		var xSpeed = lifts[l][n].movement[lifts[l][n].stage][4];
		var ySpeed = lifts[l][n].movement[lifts[l][n].stage][5];
		var stages = lifts[l][n].movement.length;
		var changedStage = false;
		
		// x
		if (startX < endX) {
			if (lifts[l][n].x < endX) {
				lifts[l][n].x += xSpeed;
				
					if(lifts[l][n].playerConnected== true){
						 player.liftX = xSpeed;
						 player.liftY = 0;
					}
			}
			if (lifts[l][n].x >= endX) {
				lifts[l][n].x = endX;
				lifts[l][n].stage++;
				changedStage = true;
				if (lifts[l][n].stage >= stages)
					lifts[l][n].stage = 0;
			}
		}
		else if (startX > endX) {
			if (lifts[l][n].x > endX) {
				lifts[l][n].x -= xSpeed;
				
				if(lifts[l][n].playerConnected== true){
						 player.liftX = -xSpeed;
						 player.liftY = 0;
					}
			}
			if (lifts[l][n].x <= endX) {
				lifts[l][n].x = endX;
				lifts[l][n].stage++;
				changedStage = true;
				if (lifts[l][n].stage >= stages)
					lifts[l][n].stage = 0;
			}
		}

		// y
		if (startY < endY) {
			if (lifts[l][n].y < endY) {
				lifts[l][n].y += ySpeed;
				if(lifts[l][n].playerConnected== true){
						 player.liftY = ySpeed;
						  player.liftX = 0;
					}
			}
			if (lifts[l][n].y >= endY) {
				lifts[l][n].y = endY;
				if (!changedStage) {
					lifts[l][n].stage++;
					if (lifts[l][n].stage >= stages)
						lifts[l][n].stage = 0;
				}
			}
		}
		else if (startY > endY) {
			if (lifts[l][n].y > endY) {
				lifts[l][n].y -= ySpeed;
				if(lifts[l][n].playerConnected== true){
						player.liftY = -ySpeed;
						 player.liftX = 0;
					}
			}
			if (lifts[l][n].y <= endY) {
				lifts[l][n].y = endY;
				if (!changedStage) {
					lifts[l][n].stage++;
					if (lifts[l][n].stage >= stages)
						lifts[l][n].stage = 0;
				}
			}
		}
		lifts[l][n].simpleX = lifts[l][n].x / 40;
		lifts[l][n].simpleY = lifts[l][n].y / 40;
	}
	lifts[l][n].playerConnected == false;
}