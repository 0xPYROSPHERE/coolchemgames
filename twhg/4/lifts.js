function simpleLift(startX, endX, startY, endY, xSpeed, ySpeed, stage, enemyType) {
	
	if(enemyType==null)
		enemyType = "simple";
	if(stage==null)
	  stage = 0;
    //xSpeed = 0;
	//ySpeed = 0;
	
	this.x = startX;
	this.y = startY;
	
	var dx = Math.floor( startX  / TILE_SIZE);
	var dy = Math.floor( startY  / TILE_SIZE);
	
	if (dx % 2 == 0 && dy % 2 == 0 || dx % 2 == 1 && dy % 2 == 1){
	 	this.typeColor = 0;				
	}
	else 
	    this.typeColor = 1;				
		
	this.simpleX = this.x / 40;
	this.playerConnected = false;
	this.simpleY = this.y / 40;
	this.startX = startX;
	this.endX = endX;
	this.startY = startY;
	this.endY = endY;
	this.xSpeed = xSpeed * 1.33;
	this.ySpeed = ySpeed * 1.33;
	this.stage = stage;
	this.enemyType = enemyType;
}
