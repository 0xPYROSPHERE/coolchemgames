function resetLifts(l) {
	for (var i = 0; i < lifts[l].length; i++) {
		 if (lifts[l][i].enemyType == "linear") {
			lifts[l][i].x = lifts[l][i].movement[0][0];
			lifts[l][i].y = lifts[l][i].movement[0][2];
			lifts[l][i].simpleX = lifts[l][i].x / 40;
			lifts[l][i].simpleY = lifts[l][i].y / 40;
			lifts[l][i].stage = 0;
		}
		
       else if (lifts[l][i].enemyType == "simplePause") {
			lifts[l][i].x = lifts[l][i].startX;
			lifts[l][i].y = lifts[l][i].startY;
			lifts[l][i].simpleX = lifts[l][i].x / 40;
			lifts[l][i].simpleY = lifts[l][i].y / 40;
			lifts[l][i].pauseTimer = 0;
			lifts[l][i].pare = false;
			lifts[l][i].stage = 0;
		} 
		
       	 else if (lifts[l][i].enemyType == "simple") {
			lifts[l][i].x = lifts[l][i].startX;
			lifts[l][i].y = lifts[l][i].startY;
			lifts[l][i].simpleX = lifts[l][i].x / 40;
			lifts[l][i].simpleY = lifts[l][i].y / 40;
			lifts[l][i].pauseTimer = 0;
			lifts[l][i].pare = false;
			lifts[l][i].stage = 0;
		} 
		
	}
}

